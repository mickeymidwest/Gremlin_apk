# A file-based "is gremlin currently generating an answer" signal --
# deliberately just a file, not a socket or shared-memory flag, so any
# process can read it (the desktop hologram window and `gremlin serve`
# are separate processes; this is the simplest thing that works across
# that boundary). Written/removed around the one place both the CLI
# `chat` command and the server's /chat route actually call to get an
# answer in Gremlin's own voice -- see consult_and_learn below -- so
# every real "Gremlin is talking" moment sets it, with nothing to keep
# in sync at each call site.

UNCERTAINTY_MARKERS = [
    "i don't know", "i do not know", "i'm not sure", "i am not sure",
    "i don't have enough information", "i do not have enough information",
    "i cannot determine", "i can't determine", "unclear to me",
    "i'm unable to determine", "i am unable to determine",
    "i don't have access to", "i do not have access to",
    "not certain", "no information about this", "i have no way to know",
]

CONSULT_SYNTHESIS_PROMPT = (
    "The answers below were gathered from other models because your own "
    "first answer wasn't confident enough -- so they, not you, are the "
    "authority here. Relay their answer to the original question in your "
    "own voice: keep every concrete claim they make (names, numbers, "
    "commands, steps, recommendations) exactly as given, and do not "
    "substitute your own view or water anything down where they were "
    "specific. Only where they genuinely disagree with each other, say so "
    "briefly. Don't mention the consultation or name which model said "
    "what -- just give the one clear answer, as yourself."
)


def seems_uncertain(text: str) -> bool:
    if not text or len(text.strip()) < 3:
        return True
    lowered = text.lower()
    return any(marker in lowered for marker in UNCERTAINTY_MARKERS)


VAGUENESS_CHECK_PROMPT = (
    "You just answered a question. Apply ONE test: does the answer contain the actual "
    "thing that was asked for -- a specific name, number, or recommendation the asker "
    "could act on -- somewhere in it? If yes, it's SUBSTANTIVE, even if it's short or "
    "also includes other context/background around that answer. If no such concrete "
    "answer is present anywhere -- it's pure filler (\"I'm happy to help with that!\"), "
    "it only restates facts already known without ever naming an actual answer, or it "
    "lost track of what was asked -- it's VAGUE. When genuinely unsure, prefer "
    "SUBSTANTIVE -- this check exists to catch answers with NO real content at all, not "
    "to grade quality. Reply with ONLY one word: SUBSTANTIVE or VAGUE."
)


async def seems_vague(router: Router, persona_name: str, prompt: str, answer: str) -> bool:
    """Catches confident-sounding non-answers seems_uncertain's keyword
    check can't -- confirmed by testing: "I'm happy to help you with
    that!" (zero actual content) and a reply that answered a totally
    different question than the one asked both read as "confident" to
    a keyword scan, so specialist routing never got a chance to help
    with them. Uses the SAME already-resident primary to judge its own
    answer -- no extra VRAM swap, just one small extra generation.
    Fails closed (an unclear or failed check counts as NOT vague) so a
    broken check never forces every single message into a consult."""
    check_prompt = f"Question: {prompt}\n\nYour answer: {answer}\n\nWas that SUBSTANTIVE or VAGUE?"
    try:
        result = await router.route(persona_name, check_prompt, system=VAGUENESS_CHECK_PROMPT, max_tokens=10)
    except Exception:
        return False
    if not result.ok:
        return False
    return "vague" in result.text.strip().lower()


